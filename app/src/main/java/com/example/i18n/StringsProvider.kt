    fun get(key: String, languageCode: String = "en", vararg args: Any): String {
        val canonicalKey = when (key) {
            "pairs_found" -> "label_pairs_found"
            "flips_count" -> "label_flips"
            "msg_memory_success" -> "msg_memory_all_found"
            "game_day_date_title" -> "game_day_date"
            "game_memory_match_title" -> "game_memory_match"
            "game_place_time_title" -> "game_place_time"
            "game_remember_objects_title" -> "game_remember_objects"
            "game_find_target_title" -> "game_find_target"
            "game_sequence_attention_title" -> "game_sequence_attention"
            "game_simple_pattern_title" -> "game_simple_pattern"
            "game_everyday_choice_title" -> "game_everyday_choice"
            else -> key
        }
        val langMap = translations[languageCode] ?: translations["en"] ?: emptyMap()
        val template = langMap[canonicalKey] ?: langMap[key] ?: translations["en"]?.get(canonicalKey) ?: translations["en"]?.get(key) ?: key
        return try {
            if (args.isNotEmpty()) String.format(template, *args) else template
        } catch (_: Exception) {
            template
        }
    }

